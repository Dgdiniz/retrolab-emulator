//! The DSP-1's data ROM.
//!
//! Beside its program the chip holds 1 024 words of constants, and its
//! arithmetic is built on them: it has no shifter, so it moves a number by
//! multiplying with a power of two from here; its reciprocal starts from a
//! table of first guesses, its square root and its sine are tables read
//! with a straight line between entries, and pi is one of the words. The
//! table below is the chip's own content, hardware data, the same in every
//! dump of it. The firmware uses nothing past word `0x32F`, and those words
//! read as `0xFFFF` here.

/// Words the memory-dump command sends back.
pub(super) const WORDS: usize = 1024;

/// `word(FRACTIONS + n)` and `word(FRACTIONS - n)` are both 2^(15-n), the
/// factor that moves a mantissa `n` places down, for `n` from 1 to 15;
/// `word(FRACTIONS)` itself is `0x7FFF`. On the upper side the entry for
/// eleven places holds 1 where 16 belongs, a slip in the chip's ROM that
/// its results carry. The lower side has no slip: read upward it is the
/// plain powers of two, which is why moving a mantissa *up* is written as a
/// shift in [`number`](super::number).
pub(super) const FRACTIONS: i32 = 0x31;

/// `word(CARRIES - n)` is 2^n for `n` from 1 to 14: the factor that brings
/// the top of a low word in beside a high word moved `n` places up. It is
/// the same run of words as [`FRACTIONS`] read from the other end, slip
/// included, here it falls on four places.
pub(super) const CARRIES: i32 = 0x40;

/// First guesses of the reciprocal: 128 words, one for each value of the
/// seven bits under a normalised mantissa's top bit.
pub(super) const RECIPROCAL_GUESSES: i32 = 0x65;

/// The square root's nodes, indexed by a mantissa's top six bits.
pub(super) const ROOT_NODES: i32 = 0xD5;

/// Sine over half a turn, 128 words from 0 to just short of pi.
pub(super) const HALF_WAVE: i32 = 0x116;

/// pi, as 3.13 fixed point.
pub(super) const PI: i32 = 0x216;

/// The four coefficients of the two short series the projection uses when
/// the camera looks too close to the horizon (see `Camera::aim`).
pub(super) const CLIP_OFFSET_CUBIC: i32 = 0x328;
pub(super) const CLIP_OFFSET_LINEAR: i32 = 0x327;
pub(super) const CLIP_COSINE_QUARTIC: i32 = 0x324;
pub(super) const CLIP_COSINE_SQUARE: i32 = 0x325;

/// One word of the ROM as the signed number the arithmetic takes it for.
/// An address outside the table reads as -1 (`0xFFFF`).
pub(super) fn word(address: i32) -> i32 {
    usize::try_from(address)
        .ok()
        .and_then(|at| CONTENTS.get(at))
        .map_or(-1, |&bits| i32::from(bits as i16))
}

/// One byte of the ROM as the memory-dump command streams it: the words in
/// order, the low byte of each first.
pub(super) fn dump_byte(position: usize) -> u8 {
    let bytes = (word((position / 2) as i32) as u16).to_le_bytes();
    bytes[position % 2]
}

