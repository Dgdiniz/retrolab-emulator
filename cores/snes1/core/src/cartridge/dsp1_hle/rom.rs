#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_powers_of_two_are_where_the_arithmetic_looks_for_them() {
        // Upward from 0x22: 1, 2, 4 ... 0x4000, a shift, in other words.
        for n in 1..=15 {
            assert_eq!(word(0x21 + n), 1 << (n - 1), "0x21 + {n}");
        }
        assert_eq!(word(FRACTIONS), 0x7fff);
        for n in 1..=15 {
            let expected = if n == 11 { 1 } else { 1 << (15 - n) };
            assert_eq!(word(FRACTIONS + n), expected, "FRACTIONS + {n}");
            assert_eq!(word(FRACTIONS - n), 1 << (15 - n), "FRACTIONS - {n}");
        }
        for n in 1..=14 {
            let expected = if n == 4 { 1 } else { 1 << n };
            assert_eq!(word(CARRIES - n), expected, "CARRIES - {n}");
        }
    }

    #[test]
    fn the_sine_table_is_half_a_turn_and_pi_is_pi() {
        assert_eq!(word(HALF_WAVE), 0);
        assert_eq!(word(HALF_WAVE + 64), 0x7fff);
        // Rising to the quarter turn, falling after it, and symmetric.
        for step in 1..64 {
            assert!(word(HALF_WAVE + step) > word(HALF_WAVE + step - 1));
            assert_eq!(word(HALF_WAVE + 128 - step), word(HALF_WAVE + step));
        }
        // 3.13 fixed point: pi x 8192, rounded.
        assert_eq!(word(PI), (std::f64::consts::PI * 8192.0).round() as i32);
    }

    #[test]
    fn outside_the_table_every_word_reads_all_ones() {
        assert_eq!(word(-1), -1);
        assert_eq!(word(CONTENTS.len() as i32), -1);
        assert_eq!(dump_byte(2 * CONTENTS.len()), 0xff);
        assert_eq!(dump_byte(2 * WORDS - 1), 0xff);
        // The dump is little-endian: word 0x22 is 0x0001.
        assert_eq!((dump_byte(0x44), dump_byte(0x45)), (0x01, 0x00));
    }
}
