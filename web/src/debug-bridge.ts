/**
 * DebugBridge, single source of truth for emulator state and the
 * panel registry. Created once at bootstrap and threaded through every
 * panel's `init()` so panels never reach into module-level globals.
 *
 * The bridge holds **mutable** runtime references (emulator, wasm
 * memory, ROM hash, run state) and the panel registry that lets one
 * panel ask another to refresh (e.g. the disassembly panel toggles a
 * breakpoint and asks the breakpoints panel to redraw). It deliberately
 * does NOT own the game loop, the WASM init, or the toolbar listeners:
 * those live in `main.ts`, `game-loop.ts`, and so on, and they call
 * into the bridge via the setters below.
 *
 * Type-wise the emulator binding is wasm-bindgen output (loose JS), so
 * we type it as `any` here and let the panels narrow at the call site
 * where useful.
 */

// Loose typing, the RetroEmulator binding is generated by wasm-bindgen
// and `audio-debugger-multi-chip.js` / `cartridge-debugger.js` etc. all
// expect untyped `emulator.foo()` calls. Keeping the type as `any`
// matches the existing JS<->WASM boundary and avoids pretending we have
// stronger guarantees than we do.
export type Emulator = any

export interface PanelHandle {
  /** Re-render the panel from current emulator state. Idempotent. */
  update(): void
  /**
   * Tear down any subscriptions / DOM listeners owned by the panel.
   * Currently never called (panels live for the whole session) but
   * present so panels can grow lifecycle hooks without API churn.
   */
  dispose(): void
}

export interface RomMeta {
  /** SHA1 (or backend-defined) hash of the loaded ROM, or null when no ROM is loaded. */
  hash: string | null
  /** Cartridge title from the header, falls back to the file name. */
  title: string
  /** Raw ROM bytes, kept around so hot-reload can re-feed them. */
  data: Uint8Array | null
  /** Original file name as picked by the user. */
  name: string
}

export interface DebugBridge {
  // -- Emulator refs ------------------------------------------------
  getEmulator(): Emulator | null
  /** Replace the live emulator instance (force reset recreates it). */
  setEmulator(emulator: Emulator, wasmMemory: WebAssembly.Memory): void
  getWasmMemory(): WebAssembly.Memory | null

  // -- Run state ----------------------------------------------------
  isRunning(): boolean
  setRunning(running: boolean): void
  isRomLoaded(): boolean
  setRomLoaded(loaded: boolean): void

  // -- ROM metadata ------------------------------------------------
  getRomMeta(): RomMeta
  setRomMeta(meta: Partial<RomMeta>): void

  // -- Focused CPU (0 = 68K, 1 = Z80) ------------------------------
  getFocusedCpu(): number

  // -- Panel registry ----------------------------------------------
  registerPanel(id: string, handle: PanelHandle): void
  unregisterPanel(id: string): void
  /** Refresh every registered panel. Cheap, each panel's update() is a no-op when there's nothing to draw. */
  refreshAll(): void
  /** Refresh a single panel by id; silently no-ops when the id is unknown. */
  refreshPanel(id: string): void

  // -- Display blit -------------------------------------------------
  /**
   * Blit the current framebuffer to the canvas once. The game loop owns
   * the actual blit (`updateDisplayOnce`); `main.ts` wires it in via
   * {@link setDisplayRefresher}. Panels call this after a paused-state
   * mutation that changes the rendered image but doesn't advance a frame
   * (e.g. a VDP layer toggle followed by `emulator.repaintFrame()`).
   * No-op until the refresher is set.
   */
  requestDisplayRefresh(): void
  /** Install the display blit callback (owned by the game loop). */
  setDisplayRefresher(fn: (() => void) | null): void
}

export function createDebugBridge(): DebugBridge {
  let emulator: Emulator | null = null
  let wasmMemory: WebAssembly.Memory | null = null
  let running = false
  let romLoaded = false
  const romMeta: RomMeta = { hash: null, title: '', data: null, name: '' }
  const panels = new Map<string, PanelHandle>()
  let displayRefresher: (() => void) | null = null

  return {
    getEmulator: () => emulator,
    setEmulator(next, memory) {
      emulator = next
      wasmMemory = memory
    },
    getWasmMemory: () => wasmMemory,

    isRunning: () => running,
    setRunning(value) {
      running = value
    },
    isRomLoaded: () => romLoaded,
    setRomLoaded(value) {
      romLoaded = value
    },

    getRomMeta: () => romMeta,
    setRomMeta(patch) {
      if (patch.hash !== undefined) romMeta.hash = patch.hash
      if (patch.title !== undefined) romMeta.title = patch.title
      if (patch.data !== undefined) romMeta.data = patch.data
      if (patch.name !== undefined) romMeta.name = patch.name
    },

    getFocusedCpu() {
      if (!emulator) return 0
      try {
        return typeof emulator.getFocusedCpu === 'function' ? emulator.getFocusedCpu() : 0
      } catch {
        return 0
      }
    },

    registerPanel(id, handle) {
      panels.set(id, handle)
    },
    unregisterPanel(id) {
      panels.delete(id)
    },
    refreshAll() {
      for (const handle of panels.values()) {
        try {
          handle.update()
        } catch (err) {
          console.error('Panel update failed:', err)
        }
      }
    },
    refreshPanel(id) {
      const handle = panels.get(id)
      if (!handle) return
      try {
        handle.update()
      } catch (err) {
        console.error(`Panel '${id}' update failed:`, err)
      }
    },

    requestDisplayRefresh() {
      try {
        displayRefresher?.()
      } catch (err) {
        console.error('Display refresh failed:', err)
      }
    },
    setDisplayRefresher(fn) {
      displayRefresher = fn
    },
  }
}
